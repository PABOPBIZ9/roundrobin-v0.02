window.PGBTranscripts = {
  events() {
    return window.PGB_TRANSCRIPT_EVENTS;
  },
  event(id) {
    return window.PGB_TRANSCRIPT_EVENTS.find((e) => e.id === id) || null;
  },
  forEvent(eventId) {
    return window.PGB_TRANSCRIPTS.filter((t) => t.event === eventId).sort((a, b) =>
      a.date === b.date ? (a.time < b.time ? 1 : -1) : a.date < b.date ? 1 : -1
    );
  },
  byId(id) {
    return window.PGB_TRANSCRIPTS.find((t) => t.id === id) || null;
  },
};
