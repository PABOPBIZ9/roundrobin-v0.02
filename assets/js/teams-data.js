window.PGBTeams = {
  registry() {
    return window.PGB_TEAMS.concat(window.PGB_EXPANSION_TEAMS || []);
  },
  all() {
    return this.registry();
  },
  bySlug(slug) {
    const key = (slug || "").toLowerCase();
    return (
      this.registry().find(
        (t) => t.slug === key || (t.aliases || []).includes(key)
      ) || null
    );
  },
  player(id) {
    for (const t of this.registry()) {
      const p = t.players.find((x) => x.id === id);
      if (p) return { player: p, team: t };
    }
    return null;
  },
  logoUrl(slug) {
    if (window.PGBTeamBrand?.logoUrl) return window.PGBTeamBrand.logoUrl(slug);
    const t = this.bySlug(slug);
    return t ? `${t.folder}01-Logos-Marks/primary.png` : "";
  },
};
